/**
 * 파티의 커버 이미지 파일명 겸 R2 오브젝트 키의 마지막 조각.
 *
 * 제목에서 뽑지 않는다. 제목은 한글과 대괄호를 담고 있어 URL·파일명으로
 * 쓰려면 인코딩이 필요하고, 문구를 다듬는 순간 이미 올린 오브젝트와 연결이
 * 끊긴다. 업체 키 + 업체 내 순번은 문구 수정에 흔들리지 않는다.
 */
export function partyImageSlug(party) {
  const ordinal = PARTIES.filter((row) => row.business === party.business).indexOf(party) + 1;
  return `${party.business}-${String(ordinal).padStart(2, '0')}`;
}

